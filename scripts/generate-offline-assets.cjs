const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const buildId = fs.readFileSync(path.join(root, '.next', 'BUILD_ID'), 'utf8').trim();
const staticDir = path.join(root, '.next', 'static');

function collect(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) return collect(file);
    if (entry.name.endsWith('.map')) return [];
    return ['/_next/static/' + path.relative(staticDir, file).split(path.sep).join('/')];
  });
}

const assets = collect(staticDir).sort();
if (!assets.length) throw new Error('No production assets found for offline caching');
fs.writeFileSync(path.join(root, 'public', 'offline-assets.js'),
  `// Generated by npm run build; do not edit.\nself.SAFI_BUILD_ID = ${JSON.stringify(buildId)};\nself.SAFI_OFFLINE_ASSETS = ${JSON.stringify(assets, null, 2)};\n`);
console.log(`Offline manifest: ${assets.length} assets for build ${buildId}`);
